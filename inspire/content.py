def quote_of_day(d: date):
    return QUOTES[(d.toordinal() * 7) % len(QUOTES)]


def history_for(d: date):
    """→ (заголовок, [(год, текст)], exact). Если на сегодня ничего нет — ближайшая дата впереди."""
    key = d.strftime("%m-%d")
    if key in HISTORY:
        return f"{d.day} {MONTHS[d.month - 1]}", HISTORY[key], True
    for i in range(1, 30):
        n = d + timedelta(days=i)
        k = n.strftime("%m-%d")
        if k in HISTORY:
            return f"{n.day} {MONTHS[n.month - 1]} · через {i} дн.", HISTORY[k], False
    return "", [], False
