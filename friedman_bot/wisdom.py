_DB = os.path.join(_BASE, "friedman.db")


def _conn():
    c = sqlite3.connect(_DB, timeout=10)
    c.execute("CREATE TABLE IF NOT EXISTS wisdom_log ("
              "day TEXT PRIMARY KEY, quote TEXT NOT NULL, ts TEXT DEFAULT CURRENT_TIMESTAMP)")
    return c


def _pick(day, used):
    """Детерминированный выбор из непоказанных. Ключ — ДЕНЬ, а не счётчик вызовов:
    в этом и была ошибка старой версии. И дедупликация по ТЕКСТУ, а не по индексу:
    список цитат пополняется, и индексы после вставки означали бы уже другое."""
    pool = [q for q in WISDOM if q not in used]
    if not pool:
        pool = list(WISDOM)          # круг пройден целиком — начинаем заново
    h = int(hashlib.sha1(day.encode("utf-8")).hexdigest(), 16)
    return pool[h % len(pool)]


def today_wisdom() -> str:
    """Одна цитата на весь день. Повторов нет, пока не показаны все.

    Раньше цитата выбиралась при КАЖДОМ вызове и сдвигала историю. Дашборд
    опрашивает API постоянно, поэтому за минуты пролистывался весь список, история
    сбрасывалась — и цитаты начинали повторяться по кругу. Теперь запись за день
    делается один раз и лежит в общей базе: и дашборд, и утренняя сводка бота
    видят одну и ту же строку.

    INSERT OR IGNORE решает гонку двух процессов: кто успел первым, того и цитата,
    второй просто прочитает готовую. Никаких блокировок не нужно.
    """
    day = datetime.now().strftime("%Y-%m-%d")
    try:
        c = _conn()
        try:
            row = c.execute("SELECT quote FROM wisdom_log WHERE day=?", (day,)).fetchone()
            if row and row[0]:
                return row[0]
            used = {r[0] for r in c.execute("SELECT quote FROM wisdom_log")}
            q = _pick(day, used)
            c.execute("INSERT OR IGNORE INTO wisdom_log(day, quote) VALUES(?,?)", (day, q))
            c.commit()
            row = c.execute("SELECT quote FROM wisdom_log WHERE day=?", (day,)).fetchone()
            return row[0] if row and row[0] else q
        finally:
            c.close()
    except Exception:
        # База недоступна — цитата всё равно должна быть, и стабильная за день.
        return _pick(day, set())


def wisdom_stats() -> dict:
    """Для проверки: сколько дней записано, сколько цитат ещё не показано."""
    try:
        c = _conn()
        try:
            used = {r[0] for r in c.execute("SELECT quote FROM wisdom_log")}
            return {"дней в базе": len(used), "всего цитат": len(WISDOM),
                    "не показано": len([q for q in WISDOM if q not in used])}
        finally:
            c.close()
    except Exception as e:
        return {"error": str(e)}
