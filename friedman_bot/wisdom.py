def _looks_russian(text: str) -> bool:
    low = text.lower()
    author = low.rsplit("—", 1)[-1] if "—" in low else low
    return any(token in author for token in _RU_DENY)


def _day_key() -> str:
    n = datetime.now()
    return f"{n.year}-{n.timetuple().tm_yday}"


def _next_static() -> str:
    """Выбирает следующую непоказанную цитату из WISDOM.
    Хранит индексы показанных в .wisdom_history.json.
    Когда все показаны — сбрасывает историю."""
    try:
        with open(_HISTORY) as f:
            hist = json.load(f)
        shown = set(hist.get("shown", []))
    except Exception:
        shown = set()

    candidates = [i for i in range(len(WISDOM)) if i not in shown]
    if not candidates:
        # все показаны — начинаем заново
        shown = set()
        candidates = list(range(len(WISDOM)))

    # детерминировано по дню (воспроизводимо при рестарте)
    n = datetime.now()
    idx = candidates[(n.timetuple().tm_yday * 137 + n.year * 31) % len(candidates)]
    shown.add(idx)
    try:
        with open(_HISTORY, "w") as f:
            json.dump({"shown": list(shown)}, f)
    except Exception:
        pass
    return WISDOM[idx]


def _generate() -> str:
    env = dict(os.environ)
    env["PATH"] = os.path.expanduser("~/.local/bin") + ":" + env.get("PATH", "")
    if os.path.exists(_TOKEN_FILE):
        with open(_TOKEN_FILE) as f:
            tok = f.read().strip()
        if tok:
            env["CLAUDE_CODE_OAUTH_TOKEN"] = tok
    r = subprocess.run(
        [_CLAUDE, "-p", _PROMPT, "--model", "haiku", "--tools", ""],
        capture_output=True, text=True, timeout=60, env=env,
    )
    text = (r.stdout or "").strip().strip(chr(34)).strip()
    if text and not text.lower().startswith("error") and len(text) < 300:
        if _looks_russian(text):
            raise RuntimeError("rejected: russian author")
        return text
    raise RuntimeError("generation failed")


def _refresh_async(key: str):
    """Генерирует свежую цитату через Claude CLI в фоне (если доступен)."""
    try:
        text = _generate()
        with open(_CACHE, "w") as f:
            json.dump({"key": key, "text": text}, f, ensure_ascii=False)
    except Exception:
        pass


def today_wisdom() -> str:
    """Одна цитата на день. Возвращает мгновенно. Кэш обновляется раз в сутки."""
    key = _day_key()
    try:
        with open(_CACHE) as f:
            cached = json.load(f)
        text = cached.get("text", "")
        if text and not _looks_russian(text):
            if cached.get("key") == key:
                return text  # сегодняшняя — отдаём как есть
            # новый день — обновляем в фоне, пока отдаём статику
            threading.Thread(target=_refresh_async, args=(key,), daemon=True).start()
    except Exception:
        threading.Thread(target=_refresh_async, args=(key,), daemon=True).start()
    return _next_static()
